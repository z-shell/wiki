import type * as PrismNamespace from "prismjs";

export function registerZShellLanguages(Prism: typeof PrismNamespace): void {
  Prism.languages.zsh = Prism.languages.extend("bash", {});

  const zshBuiltins = [
    "autoload",
    "bindkey",
    "builtin",
    "compctl",
    "compdump",
    "compinit",
    "compdef",
    "compfiles",
    "compgroups",
    "compquote",
    "comptags",
    "comptry",
    "compvalues",
    "declare",
    "dirs",
    "disable",
    "disown",
    "emulate",
    "enable",
    "fc",
    "float",
    "functions",
    "getcap",
    "getln",
    "getopts",
    "history",
    "integer",
    "jobs",
    "let",
    "limit",
    "local",
    "log",
    "noglob",
    "popd",
    "print",
    "printf",
    "pushd",
    "pushln",
    "pwd",
    "read",
    "readonly",
    "sched",
    "set",
    "setcap",
    "setopt",
    "shift",
    "source",
    "stat",
    "suspend",
    "ttyctl",
    "type",
    "typeset",
    "ulimit",
    "umask",
    "unalias",
    "unfunction",
    "unhash",
    "unlimit",
    "unset",
    "unsetopt",
    "vared",
    "wait",
    "whence",
    "where",
    "which",
    "zcompile",
    "zformat",
    "zle",
    "zmodload",
    "zparseopts",
    "zpty",
    "zregexparse",
    "zsocket",
    "zstyle",
    "ztcp",
  ];

  // ZSH-specific builtins — inserted before 'function' so they take priority
  Prism.languages.insertBefore("zsh", "function", {
    "zsh-builtin": {
      pattern: new RegExp(String.raw`(?<lb>^|[\s;|&])(?:${zshBuiltins.join("|")})(?=[\s;|&]|$)`),
      lookbehind: true,
      alias: "builtin",
    },
  });

  // Expansion flags and parameter tokens — inserted before 'variable' for priority
  Prism.languages.insertBefore("zsh", "variable", {
    "zsh-expansion-flag": {
      pattern: /\$\{\([^)]*\)/,
      alias: "attr-value",
    },
    "zsh-special-parameter": {
      pattern: /\$(?:[#*@?!$]|[A-Za-z_]\w*|\{[^}\n]+\})/,
      alias: "variable",
    },
    "zsh-glob-qualifier": {
      pattern: /(?<lb>^|[^\w])(?:\*\*\/)?\*[^ \n]*(?:\([^)]+\))/,
      lookbehind: true,
      alias: "operator",
    },
  });

  Prism.languages.zi = Prism.languages.extend("zsh", {});
  const ziIces = [
    "aliases",
    "as",
    "atclone",
    "atinit",
    "atload",
    "atpull",
    "autoload",
    "bindmap",
    "blockf",
    "bpick",
    "cargo",
    "cloneonly",
    "cloneopts",
    "compile",
    "countdown",
    "cp",
    "depth",
    "eval",
    "extract",
    "fbin",
    "ferc",
    "fmod",
    "from",
    "fsrc",
    "gem",
    "has",
    "id-as",
    "if",
    "light-mode",
    "load",
    "lucid",
    "make",
    "multisrc",
    "mv",
    "nocd",
    "nocompile",
    "nocompletions",
    "node",
    "notify",
    "pick",
    "pip",
    "proto",
    "pullopts",
    "reset",
    "reset-prompt",
    "run-atpull",
    "sbin",
    "service",
    "silent",
    "src",
    "submods",
    "subscribe",
    "subst",
    "teleid",
    "trackbinds",
    "trigger-load",
    "unload",
    "ver",
    "wait",
    "wrap",
  ];
  const ziCommands = [
    "analytics",
    "annex",
    "as",
    "bindkey",
    "bindmap",
    "cdclear",
    "cdisable",
    "cdlist",
    "cdreplay",
    "cenable",
    "clist",
    "compile",
    "create",
    "creinstall",
    "cuninstall",
    "default-ice",
    "delete",
    "depth",
    "for",
    "from",
    "has",
    "ice",
    "icemods",
    "id-as",
    "is-snippet",
    "light",
    "light-mode",
    "list",
    "load",
    "lucid",
    "module",
    "nocd",
    "pack",
    "remove",
    "report",
    "self-update",
    "shim-list",
    "snippet",
    "source",
    "status",
    "unload",
    "update",
    "wait",
  ];
  // zi-ice must fire before zsh-builtin: both match words like 'wait'/'src',
  // but in zi blocks ice modifiers take priority over shell builtins.
  Prism.languages.insertBefore("zi", "zsh-builtin", {
    "zi-ice": {
      pattern: new RegExp(String.raw`\b(?:${ziIces.join("|")})\b(?=(?:["'=\s]|$))`),
      alias: "builtin",
    },
  });
  Prism.languages.insertBefore("zi", "function", {
    "zi-command": {
      pattern: new RegExp(String.raw`\b(?:zi|zinit)\s+(?:${ziCommands.join("|")})\b`),
      inside: {
        keyword: /\b(?:zi|zinit)\b/,
        function: new RegExp(String.raw`\b(?:${ziCommands.join("|")})\b`),
      },
    },
  });

  Prism.languages.zunit = Prism.languages.extend("zsh", {});
  Prism.languages.insertBefore("zunit", "function", {
    "zunit-directive": {
      pattern: /@\b(?:setup|teardown|test)\b/,
      alias: "keyword",
    },
    "zunit-assertion": {
      pattern:
        /\b(?:assert|assert_contains|assert_empty|assert_equal|assert_false|assert_match|assert_not_contains|assert_not_empty|assert_not_equal|assert_not_match|assert_status|assert_true)\b/,
      alias: "function",
    },
    "zunit-command": {
      pattern: /(?<lb>^|[\s;|&])zunit(?=[\s;|&]|$)/,
      lookbehind: true,
      alias: "builtin",
    },
  });
}
